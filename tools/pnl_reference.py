"""Reference values for tests/test_pnl.cpp, from panam's own PNL/EPNL functions.

  PANAM=/path/to/panam python tools/pnl_reference.py > reference.inc

(numpy is all it needs besides panam's flight_acoustics.py.)  Prints the C++
initializers that test_pnl.cpp embeds between its `clang-format off/on` lines.  Inputs are rounded to 0.1 dB and printed as decimal literals, so
Python and C++ parse the same doubles; histories are built as base[i] + envelope[k] (+ tone
add[k] in one band), the same IEEE additions on both sides.
"""
import os
import sys
import numpy as np
sys.path.insert(0, os.environ.get('PANAM', '.'))
import flight_acoustics as fa  # noqa: E402

F = fa.PNL_BAND_FREQUENCIES
rng = np.random.default_rng(20261005)


def r1(x):
    return [float(f'{v:.1f}') for v in x]


def lit(v):
    if v == -np.inf:
        return '-inf'
    if v == np.inf:
        return 'inf'
    return repr(float(v))


spectra = []
flat = [70.0] * 24
spectra.append(('flat 70 dB', flat))
for band, add, name in [(13, 10.0, '1 kHz tone +10'), (10, 10.0, '500 Hz tone +10'),
                        (7, 10.0, '250 Hz tone +10'), (2, 10.0, '80 Hz tone +10 (band 3)'),
                        (3, 10.0, '100 Hz tone +10 (band 4)'), (23, 10.0, '10 kHz tone +10 (band 24)'),
                        (20, 8.0, '5 kHz tone +8'), (21, 8.0, '6.3 kHz tone +8'),
                        (16, 25.0, '2 kHz tone +25 (F >= 20)'), (14, 2.4, '1.25 kHz tone +2.4 (1.5 <= F < 3)'),
                        (1, 12.0, '63 Hz tone +12 (band 2)')]:
    s = list(flat)
    s[band] += add
    spectra.append((name, r1(s)))
# Band 24 encircled on a slope: SPL'(24) = SPL(23) + s(23), and s(23) is not zero.
s = [80.0 - 1.5 * i for i in range(24)]
s[23] += 10.0
spectra.append(('falling 1.5 dB a band, 10 kHz tone +10', r1(s)))
# A rise that levels off: the slope goes 2, 5.5, then exactly 0, so only step 3(b) -- "zero
# or negative" -- encircles the 1 kHz band; 3(a) never fires (the 2 -> 5.5 change is under 5).
s = list(flat)
s[12] += 2.0
s[13] += 7.5
s[14] += 7.5
spectra.append(('rise to a plateau at 1 and 1.25 kHz (step 3(b) at a zero slope)', r1(s)))
# A helicopter-like spectrum: falling with frequency, a main-rotor hump, a tail-rotor tone.
heli = 88.0 - 9.0 * np.log2(F / 50.0) ** 1.1 + 6.0 * np.exp(-((np.log2(F / 1600.0)) ** 2) / 0.8)
heli[3] += 9.0
spectra.append(('helicopter-like, tail-rotor tone at 100 Hz', r1(heli)))
# Levels straddling SPL(d), SPL(e), SPL(b) and SPL(a): every noy region.
spectra.append(('noy regions low', r1([49.5, 44.0, 38.0, 35.0, 31.0, 28.0, 25.0, 22.0, 19.0, 17.0, 16.5, 20.0,
                                       24.0, 26.0, 24.0, 22.0, 19.0, 16.0, 15.0, 15.5, 16.0, 11.0, 18.0, 22.0])))
spectra.append(('noy regions high', r1([95.0, 90.0, 91.0, 85.0, 84.0, 80.0, 78.0, 80.0, 96.0, 75.0, 72.0, 70.0,
                                        68.0, 66.0, 64.0, 62.0, 60.0, 58.0, 56.0, 54.0, 52.0, 50.0, 47.0, 52.0])))
spectra.append(('silence', [0.0] * 24))
part = list(flat)
for i in range(16, 24):
    part[i] = 0.0
spectra.append(('upper bands silent', part))
for n in range(8):
    base = 75.0 - 1.5 * np.arange(24) * rng.random() + 6.0 * rng.standard_normal(24)
    spectra.append((f'random {n}', r1(base)))

print('// clang-format off')
print('// Generated by tools/pnl_reference.py from panam flight_acoustics (eeb040b).')
print('const std::vector<SpectrumCase> spectrum_cases = {')
for name, s in spectra:
    s = np.asarray(s, float)
    pnl = fa.perceived_noise_level(s)
    c, band = fa.tone_correction(s)
    n = fa.noys(s)
    print(f'    {{"{name}", {{{", ".join(lit(v) for v in s)}}},')
    print(f'        {lit(pnl)}, {lit(c)}, {band},')
    print(f'        {{{", ".join(lit(v) for v in n)}}}}},')
print('};')

# Histories: base[i] + envelope[k], plus `add[k]` in one band.
histories = []
env40 = r1(60.0 * np.exp(-((np.arange(40) - 22.0) / 7.0) ** 2) - 30.0)
histories.append(('approach-like pass, 40 frames', r1(heli - 10.0), env40, 13,
                  r1(3.0 + 3.0 * np.sin(np.arange(40) * 1.3))))
# panam's own band-sharing case: tone in every frame but the peak, peak frame 4 dB up.
bs_env = [0.0, 0.0, 0.0, 4.0, 0.0, 0.0, 0.0]
bs_add = [10.0, 10.0, 10.0, 0.0, 10.0, 10.0, 10.0]
histories.append(('panam band-sharing case', flat, bs_env, 13, bs_add))
histories.append(('panam contiguous dip case', flat, [-30.0, 10.0, -2.0, 10.0, -30.0], 13, [0.0] * 5))
histories.append(('constant 20 s', flat, [0.0] * 40, 13, [0.0] * 40))
env60 = r1(-25.0 + 25.0 * np.exp(-((np.arange(60) - 30.0) / 9.0) ** 2) + 1.5 * rng.standard_normal(60))
add60 = r1(np.where(rng.random(60) < 0.5, 9.0, 0.5))
histories.append(('noisy envelope, flickering tone', r1(heli - 8.0), env60, 20, add60))
histories.append(('peak in the first frame', r1(heli - 5.0), [6.0, 4.0, 1.0, -3.0, -8.0, -12.0, -16.0], 7,
                  [0.0, 8.0, 8.0, 8.0, 0.0, 0.0, 0.0]))
histories.append(('peak in the last frame, silent start', r1(heli - 5.0),
                  [-200.0, -200.0, -15.0, -10.0, -6.0, -2.0, 0.0], 10, [0.0, 0.0, 0.0, 6.0, 6.0, 6.0, 0.0]))

print('const std::vector<HistoryCase> history_cases = {')
for name, base, env, band, add in histories:
    base = np.asarray(base, float)
    hist = np.empty((len(env), 24))
    for k, e in enumerate(env):
        for i in range(24):
            hist[k, i] = base[i] + e
        hist[k, band] = hist[k, band] + add[k]
    on = fa.effective_perceived_noise_level(hist, dt=0.5, bandshare_adjustment=True)
    off = fa.effective_perceived_noise_level(hist, dt=0.5, bandshare_adjustment=False)
    km = int(np.nanargmax(on['pnlt']))
    print(f'    {{"{name}",')
    print(f'        {{{", ".join(lit(v) for v in base)}}},')
    print(f'        {{{", ".join(lit(v) for v in env)}}}, {band},')
    print(f'        {{{", ".join(lit(v) for v in add)}}},')
    for r in (on, off):
        print(f'        {{{lit(r["epnl"])}, {lit(r["pnltm"])}, {lit(r["duration_correction_db"])}, '
              f'{r["k1"]}, {r["k2"]}, {km}, {str(r["clipped"]).lower()}}},')
    print(f'        {{{", ".join(lit(v) for v in on["pnlt"])}}}}},')
print('};')
print('// clang-format on')
