void check_close(double got, double expected, double tolerance)
{
    REQUIRE(std::fabs(got - expected) <= tolerance);
}

// The bands the EGA reference values were generated at.
const std::vector<double> kBands = {50.0, 100.0, 200.0, 500.0, 1000.0, 2000.0};

